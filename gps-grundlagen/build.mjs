// Bundles the ES modules into js/bundle.js (classic script) so index.html
// also runs when opened via double-click over file://, where browsers block ES modules.
// Run after any change in js/: node build.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const order = ['svg.js', 'data.js', 'figures.js', 'app.js'];
const dir = new URL('./js/', import.meta.url);
const parts = order.map((f) => {
  const src = readFileSync(new URL(f, dir), 'utf8')
    .replace(/^import .*$/gm, '')
    .replace(/^export (const|function|let) /gm, '$1 ');
  return `// ---- ${f} ----\n${src}`;
});
writeFileSync(new URL('bundle.js', dir), `// Generated by build.mjs — do not edit by hand\n(() => {\n'use strict';\n${parts.join('\n')}\n})();\n`);
console.log('js/bundle.js written');
